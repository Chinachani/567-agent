/** DOM physical codes to Linux evdev codes (the portal does not accept XKB's +8 offset). */
export function waylandKeycode(code: string): number | undefined {
	if (/^Key[A-Z]$/.test(code)) return letterCodes[code.charAt(3)];
	if (/^Digit[0-9]$/.test(code)) return code === "Digit0" ? 11 : Number(code.slice(5)) + 1;
	const fn = /^F([1-9]|1[0-2])$/.exec(code);
	if (fn) return Number(fn[1]) <= 10 ? 58 + Number(fn[1]) : 76 + Number(fn[1]);
	return namedCodes[code];
}
