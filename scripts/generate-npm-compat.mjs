import { mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const root = fileURLToPath(new URL("../", import.meta.url));
export const packages = {
	"capability-sdk": "packages/capability-sdk",
	"plugin-sdk": "packages/plugins/plugin-sdk",
	"plugin-vite": "packages/plugins/plugin-vite",
	"plugin-cli": "packages/plugins/plugin-cli",
	"theme-sdk": "packages/theme-sdk",
	"theme-ui": "packages/theme-ui",
	ui: "packages/ui",
};

async function save(path, contents) {
	await mkdir(dirname(path), { recursive: true });
	await writeFile(path, contents);
}

// Keep the published implementation as the only source of runtime identity.
// New packages forward public exports rather than bundling another SDK copy.
export async function generateCompatPackages(repoRoot = root, selected = Object.keys(packages)) {
	for (const name of selected) {
		if (!Object.hasOwn(packages, name)) throw new Error(`Unknown compatibility package: ${name}`);
		const originalDir = join(repoRoot, packages[name]);
		const original = JSON.parse(await readFile(join(originalDir, "package.json"), "utf8"));
		const targetDir = join(repoRoot, "packages/npm-compat", name);
		const exports = {};
		for (const [subpath, value] of Object.entries(original.exports)) {
			if (subpath.endsWith(".css")) {
				const target = `./dist/${subpath.slice(2)}`;
				await mkdir(dirname(join(targetDir, target)), { recursive: true });
				await copyFile(join(originalDir, value), join(targetDir, target));
				exports[subpath] = target;
				continue;
			}
			const stem = subpath === "." ? "index" : subpath.slice(2);
			const specifier = original.name + (subpath === "." ? "" : subpath.slice(1));
			const forwarding = `export * from "${specifier}";\n`;
			const generated = "// Generated by scripts/generate-npm-compat.mjs.\n" + forwarding;
			await save(join(targetDir, `src/${stem}.ts`), generated);
			await save(join(targetDir, `dist/${stem}.js`), generated);
			await save(join(targetDir, `dist/${stem}.d.ts`), generated);
			exports[subpath] = typeof value === "string" ? `./dist/${stem}.js` : {
				types: `./dist/${stem}.d.ts`, import: `./dist/${stem}.js`,
			};
		}
		const bin = {};
		for (const [command, originalPath] of Object.entries(original.bin ?? {})) {
			const stem = `bin/${command}`;
			bin[command] = `./dist/${stem}.js`;
			// Resolve the public root first; package exports forbid deep imports.
			const launch = `#!/usr/bin/env node\nimport { dirname, resolve } from "node:path";\nimport { fileURLToPath, pathToFileURL } from "node:url";\nconst entry = fileURLToPath(import.meta.resolve("${original.name}"));\nawait import(pathToFileURL(resolve(dirname(entry), "${originalPath.replace("./dist/", "")}")).href);\n`;
			await save(join(targetDir, `${bin[command]}`), launch);
		}
		const manifest = {
			name: `@567agent/${name}`, version: original.version, type: "module",
			description: `567 Agent public entry for ${original.name}; shared runtime identity is preserved.`,
			...(original.author ? { author: original.author } : {}),
			main: "./dist/index.js", types: "./dist/index.d.ts", exports, license: "Apache-2.0",
			...(original.repository ? {
				repository: { ...original.repository, directory: `packages/npm-compat/${name}` },
			} : {}),
			...(Object.keys(bin).length ? { bin } : {}), files: ["dist", "README.md", "LICENSE", "NOTICE"],
			scripts: {
				build: `node ../../../scripts/generate-npm-compat.mjs ${name}`,
				prepack: `node ../../../scripts/generate-npm-compat.mjs ${name}`,
			},
			dependencies: { [original.name]: original.version },
			...(original.peerDependencies ? { peerDependencies: original.peerDependencies } : {}),
			...(original.peerDependenciesMeta ? { peerDependenciesMeta: original.peerDependenciesMeta } : {}),
			publishConfig: original.publishConfig,
		};
		for (const name of ["LICENSE", "NOTICE"]) {
			await copyFile(join(repoRoot, name), join(targetDir, name));
		}
		await save(join(targetDir, "package.json"), `${JSON.stringify(manifest, null, "\t")}\n`);
		await save(join(targetDir, "README.md"), `# @567agent/${name}\n\n此包转发 ${original.name} 的公开入口，保留同一份运行时实例和旧插件兼容。\n\n发布前运行本包 build；旧包仍可继续使用。此目录由 scripts/generate-npm-compat.mjs 生成。\n`);
	}
	if (repoRoot === root) {
		execFileSync(process.execPath, [join(root, "node_modules/@biomejs/biome/bin/biome"), "format", "--write", ...selected.map((name) => join(root, "packages/npm-compat", name))], { stdio: "pipe" });
	}
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	await generateCompatPackages(root, process.argv.length > 2 ? process.argv.slice(2) : undefined);
}
